#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
# Real local-adoption acceptance. Supply existing, non-store SDKs; never
# download or build a compiler here. CABAL_PURIFIER_CLI selects the CLI.
# Usage: tests/host-runtime.sh GHC-BIN-DIR CABAL-BIN-DIR EVIDENCE-DIR
set -euo pipefail
root=$(pwd -P)
cli=${CABAL_PURIFIER_CLI:?Set CABAL_PURIFIER_CLI to the CLI under test}
export PATH="$1:$2:$PATH"
mkdir -p "$3"
evidence=$(cd "$3" && pwd -P)
host_ghc=$(command -v ghc)
host_cabal=$(command -v cabal)
python3 - "$host_ghc" "$host_cabal" "$(ghc --print-libdir)" <<'PY'
from pathlib import Path
import sys
for value in sys.argv[1:]:
    actual = Path(value).resolve()
    assert not str(actual).startswith('/nix/store/'), actual
PY
printf '%s\n' "$host_ghc" "$host_cabal" "$(ghc --print-libdir)" > "$evidence/host-paths.txt"
ghc --info > "$evidence/ghc-info.txt"
cabal --version > "$evidence/cabal-version.txt"
work=$(mktemp -d)
trap 'chmod -R u+w "$work"; rm -rf "$work"' EXIT
cp -R "$root/tests/fixtures/app" "$work/app"
chmod -R u+w "$work/app"
cd "$work/app"
rm cabal-purifier.lock.json
sha256sum Main.hs cabal.project hello.cabal > "$evidence/project-before.sha256"
"$cli" lock > "$evidence/lock.stdout" 2> "$evidence/lock.stderr"
cp cabal-purifier.lock.json "$evidence/lock.json"
"$cli" prefetch > "$evidence/prefetch.sh" 2> "$evidence/prefetch.stderr"
# The export is generated by the tested CLI and retained for inspection.
source "$evidence/prefetch.sh"
test "$(command -v ghc)" = "$host_ghc"
test ! -e cabal-purifier.lock.prefetch/toolchain
test ! -e dist-newstyle/cabal-purifier/toolchain
printf '%s\n' "$(command -v ghc)" "$(command -v cabal)" > "$evidence/after-paths.txt"
export http_proxy=http://127.0.0.1:9 https_proxy=http://127.0.0.1:9
export HTTP_PROXY=http://127.0.0.1:9 HTTPS_PROXY=http://127.0.0.1:9
export ALL_PROXY=http://127.0.0.1:9 all_proxy=http://127.0.0.1:9 NO_PROXY= no_proxy=
cabal run hello > "$evidence/runtime.txt" 2> "$evidence/runtime.stderr"
grep -q 'hello purified ' "$evidence/runtime.txt"
cp dist-newstyle/cache/plan.json "$evidence/plan.json"
sha256sum Main.hs cabal.project hello.cabal > "$evidence/project-after.sha256"
cmp "$evidence/project-before.sha256" "$evidence/project-after.sha256"
python3 - "$evidence/plan.json" "$(ghc --numeric-version)" <<'PY'
import json, sys
assert json.load(open(sys.argv[1]))['compiler-id'] == 'ghc-' + sys.argv[2]
PY
# A genuine lock/SDK version mismatch must fail before prefetch and execution.
python3 - <<'PY'
import base64, hashlib, json
from pathlib import Path
p = Path('cabal-purifier.lock.json')
lock = json.loads(p.read_text())
for plan in lock['systems'].values():
    plan['compiler'] = 'ghc-0.0.0-mismatch'
body = {k:v for k,v in lock.items() if k != 'hash'}
raw = json.dumps(body, sort_keys=True, separators=(',', ':'), ensure_ascii=False).encode()
lock['hash'] = 'sha256-' + base64.b64encode(hashlib.sha256(raw).digest()).decode()
p.write_text(json.dumps(lock, indent=2) + '\n')
PY
if "$cli" prefetch > "$evidence/mismatch-prefetch.log" 2>&1; then
  echo 'prefetch accepted a different locked compiler' >&2; exit 1
fi
grep -q 'lock names ghc-0.0.0-mismatch' "$evidence/mismatch-prefetch.log"
if cabal run hello > "$evidence/mismatch-shim.log" 2>&1; then
  echo 'shim accepted a different locked compiler' >&2; exit 1
fi
grep -q 'lock names ghc-0.0.0-mismatch' "$evidence/mismatch-shim.log"
echo 'host-runtime.sh: capture, dependency-only prefetch, offline execution and mismatch checks passed'
